// Generates src/math/atan_table128.hpp: atan(j/128) for j = 0..128 as the
// correctly rounded double plus the remainder (hi + lo ~ 106 bits), and
// pi/2 and pi as double-doubles. Computed with the double-double reference
// in tests/reference/wide.hpp.
//
// Usage: gen_atan_table <output header>

#include "../tests/reference/wide.hpp"

#include <cstdio>

int main(const int argument_count, char** const arguments) {
    if (argument_count != 2) {
        std::fputs("usage: gen_atan_table <output header>\n", stderr);
        return 2;
    }
    std::FILE* const output = std::fopen(arguments[1], "w");
    if (output == nullptr) return 1;
    std::fputs("#pragma once\n\n"
               "// Generated by tools/gen_atan_table.cpp. Do not edit by hand.\n"
               "// atan(j/128) for j = 0..128 as hi + lo: hi is the correctly rounded double,\n"
               "// lo the remainder (reference error ~1e-32).\n\n"
               "namespace stx_auxlib::math::detail {\n\n"
               "struct AtanEntry final {\n"
               "    double hi;\n    double lo;\n};\n\n"
               "// 129 entries of 16 bytes: 2 KiB.\n"
               "alignas(64) inline constexpr AtanEntry atan_table_129[129] = {\n",
               output);
    for (int j = 0; j <= 128; ++j) {
        const wide::Wide value = wide::atan_reference(wide::Wide{static_cast<double>(j) / 128.0, 0.0});
        const wide::Wide entry = wide::two_sum(value.hi, value.lo);
        std::fprintf(output, "    {%a, %a}%s\n", entry.hi, entry.lo + 0.0, j == 128 ? "" : ",");
    }
    std::fputs("};\n", output);
    const wide::Wide half_pi = wide::two_sum(wide::half_pi_1, wide::half_pi_2);
    std::fprintf(output,
                 "\n// pi/2 and pi as double-doubles.\n"
                 "inline constexpr double atan_half_pi_hi = %a;\n"
                 "inline constexpr double atan_half_pi_lo = %a;\n"
                 "inline constexpr double atan_pi_hi = %a;\n"
                 "inline constexpr double atan_pi_lo = %a;\n\n"
                 "} // namespace stx_auxlib::math::detail\n",
                 half_pi.hi, half_pi.lo, 2.0 * half_pi.hi, 2.0 * half_pi.lo);
    std::fclose(output);
    return 0;
}
