// Generates src/math/sincos_table256.hpp: sin and cos of
// k*pi/128 for k = 0..255, each as the correctly rounded double plus the
// remainder (hi + lo ~ 106 bits), and the three-part pi/128 used for
// Cody-Waite reduction. Computed with the double-double reference in
// tests/reference/wide.hpp.
//
// The hi parts were checked once against bfft's mpmath table
// (falseywinchnet/bfft a56bc4c, src/detail/generated/bruun_sincos_table256.hpp):
// all 256 entries agree bit for bit, apart from the exact zeros at pi/2, pi
// and 3pi/2, where mpmath's 100-digit pi leaves ~1e-102 and this table has 0.
//
// Usage: gen_sincos_table <output header>

#include "../tests/reference/wide.hpp"

#include <bit>
#include <cmath>
#include <cstdint>
#include <cstdio>

namespace {

// j * pi/128 in double-double for |j| <= 32, from the three-part pi/2.
wide::Wide angle(const int j) {
    const double parts[3] = {wide::half_pi_1 / 64.0, wide::half_pi_2 / 64.0,
                             wide::half_pi_3 / 64.0};
    wide::Wide sum{0.0, 0.0};
    for (const double part : parts) {
        const double p = static_cast<double>(j) * part;
        const double e = std::fma(static_cast<double>(j), part, -p);
        sum = wide::add(sum, wide::Wide{p, e});
    }
    return sum;
}

// sin and cos of k*pi/128: k = 64 * quadrant + j with |j| <= 32.
wide::WideSinCos exact_entry(const int k) {
    int quadrant = k / 64;
    int j = k % 64;
    if (j > 32) {
        j -= 64;
        quadrant += 1;
    }
    const wide::WideSinCos base = wide::series(angle(j));
    wide::WideSinCos result{};
    switch (quadrant & 3) {
    case 0: result = base; break;
    case 1: result = wide::WideSinCos{base.c, wide::negate(base.s)}; break;
    case 2: result = wide::WideSinCos{wide::negate(base.s), wide::negate(base.c)}; break;
    default: result = wide::WideSinCos{wide::negate(base.c), base.s}; break;
    }
    return result;
}

// The rounded double and the remainder. Adding +0 makes the exact zeros +0.
wide::Wide normalized(const wide::Wide value) {
    const wide::Wide sum = wide::two_sum(value.hi, value.lo);
    const wide::Wide result{sum.hi + 0.0, sum.lo + 0.0};
    return result;
}

// Keeps the leading 27 significant bits, so a product with any integer below
// 2^26 is exact.
double truncate_27(const double value) {
    const std::uint64_t bits = std::bit_cast<std::uint64_t>(value);
    const std::uint64_t kept = bits & ~((std::uint64_t{1} << 26) - 1);
    const double result = std::bit_cast<double>(kept);
    return result;
}

// Keeps the leading 15 significant bits, so a product with any integer below
// 2^38 is exact.
double truncate_15(const double value) {
    const std::uint64_t bits = std::bit_cast<std::uint64_t>(value);
    const std::uint64_t kept = bits & ~((std::uint64_t{1} << 38) - 1);
    const double result = std::bit_cast<double>(kept);
    return result;
}

// Renormalizes an expansion (an exact sum of doubles) so its first term is
// the sum rounded to double and later terms hold the rest, by two-sum sweeps.
void renormalize(double (&terms)[5]) {
    for (int sweep = 0; sweep < 4; ++sweep) {
        for (int i = 4; i > 0; --i) {
            const wide::Wide pair = wide::two_sum(terms[i - 1], terms[i]);
            terms[i - 1] = pair.hi;
            terms[i] = pair.lo;
        }
    }
}

} // namespace

int main(const int argument_count, char** const arguments) {
    if (argument_count != 2) {
        std::fputs("usage: gen_sincos_table <output header>\n", stderr);
        return 2;
    }
    std::FILE* const output = std::fopen(arguments[1], "w");
    if (output == nullptr) return 1;
    std::fputs("#pragma once\n\n"
               "// Generated by tools/gen_sincos_table.cpp. Do not edit by hand.\n"
               "// sin and cos of k*pi/128 for k = 0..255, each as hi + lo: hi is the\n"
               "// correctly rounded double, lo the remainder (reference error ~1e-32).\n\n"
               "namespace stx_auxlib::math::detail {\n\n"
               "struct SinCosEntry final {\n"
               "    double s;\n    double c;\n    double s_lo;\n    double c_lo;\n};\n\n"
               "// 256 entries of 32 bytes: 8 KiB, two entries per 64-byte line.\n"
               "alignas(64) inline constexpr SinCosEntry sincos_table_256[256] = {\n",
               output);
    for (int k = 0; k < 256; ++k) {
        const wide::WideSinCos entry = exact_entry(k);
        const wide::Wide s = normalized(entry.s);
        const wide::Wide c = normalized(entry.c);
        std::fprintf(output, "    {%a, %a, %a, %a}%s\n", s.hi, c.hi, s.lo, c.lo,
                     k == 255 ? "" : ",");
    }
    std::fputs("};\n", output);

    // pi/128 for Cody-Waite reduction: two 27-bit parts and a double rest.
    const double t1 = wide::half_pi_1 / 64.0;
    const double t2 = wide::half_pi_2 / 64.0;
    const double t3 = wide::half_pi_3 / 64.0;
    const double p1 = truncate_27(t1);
    const wide::Wide rest = wide::add(wide::Wide{t1 - p1, 0.0},
                                      wide::add(wide::Wide{t2, 0.0}, wide::Wide{t3, 0.0}));
    const double p2 = truncate_27(rest.hi);
    const double p3 = (rest.hi - p2) + rest.lo;
    std::fprintf(output,
                 "\n// pi/128 = step_1 + step_2 + step_3 (~133 bits); step_1 and step_2 have\n"
                 "// 27 significant bits, so q * step_1 and q * step_2 are exact for |q| < 2^26.\n"
                 "inline constexpr double sincos_step_1 = %a;\n"
                 "inline constexpr double sincos_step_2 = %a;\n"
                 "inline constexpr double sincos_step_3 = %a;\n",
                 p1, p2, p3);

    // pi/128 for the medium range (2^20 < |x| <= 2^32, |q| < 2^38): eight
    // 15-bit parts and a double rest, peeled exactly from the four-double
    // pi/2 (each part is the leading 15 bits of what remains).
    double terms[5] = {wide::half_pi_1 / 64.0, wide::half_pi_2 / 64.0, wide::half_pi_3 / 64.0,
                       wide::half_pi_4 / 64.0, 0.0};
    renormalize(terms);
    std::fputs("\n// pi/128 = medium_step[0] + ... + medium_step[7] + medium_step_rest\n"
               "// (~173 bits); each part has 15 significant bits, so q * part is exact for\n"
               "// |q| < 2^38 (|x| <= 2^32).\n"
               "inline constexpr double sincos_medium_step[8] = {\n",
               output);
    for (int part = 0; part < 8; ++part) {
        const double piece = truncate_15(terms[0]);
        terms[0] -= piece;  // exact: piece is terms[0]'s leading bits
        renormalize(terms);
        std::fprintf(output, "    %a%s\n", piece, part == 7 ? "" : ",");
    }
    const double medium_rest = ((terms[0] + terms[1]) + terms[2]) + terms[3];
    std::fprintf(output,
                 "};\ninline constexpr double sincos_medium_step_rest = %a;\n\n"
                 "} // namespace stx_auxlib::math::detail\n",
                 medium_rest);
    std::fclose(output);
    return 0;
}
