// Generates src/math/exp_table256.hpp: 2^(j/256) for
// j = 0..255 as the correctly rounded double plus the remainder (hi + lo
// ~ 106 bits), and the three-part ln2/256 used for Cody-Waite reduction.
// Computed with the double-double reference in tests/reference/wide.hpp,
// as e^(j * ln2/256).
//
// Usage: gen_exp_table <output header>

#include "../tests/reference/wide.hpp"

#include <bit>
#include <cmath>
#include <cstdint>
#include <cstdio>

namespace {

// j * ln2/256 in double-double, from the three-part ln 2 (exact scaling).
wide::Wide angle(const int j) {
    const double parts[3] = {wide::ln2_1 / 256.0, wide::ln2_2 / 256.0, wide::ln2_3 / 256.0};
    wide::Wide sum{0.0, 0.0};
    for (const double part : parts) {
        const double p = static_cast<double>(j) * part;
        const double e = std::fma(static_cast<double>(j), part, -p);
        sum = wide::add(sum, wide::Wide{p, e});
    }
    return sum;
}

// Keeps the leading 34 significant bits, so a product with any integer below
// 2^19 is exact.
double truncate_34(const double value) {
    const std::uint64_t bits = std::bit_cast<std::uint64_t>(value);
    const std::uint64_t kept = bits & ~((std::uint64_t{1} << 19) - 1);
    const double result = std::bit_cast<double>(kept);
    return result;
}

} // namespace

int main(const int argument_count, char** const arguments) {
    if (argument_count != 2) {
        std::fputs("usage: gen_exp_table <output header>\n", stderr);
        return 2;
    }
    std::FILE* const output = std::fopen(arguments[1], "w");
    if (output == nullptr) return 1;
    std::fputs("#pragma once\n\n"
               "// Generated by tools/gen_exp_table.cpp. Do not edit by hand.\n"
               "// 2^(j/256) for j = 0..255 as hi + lo: hi is the correctly rounded double,\n"
               "// lo the remainder (reference error ~1e-32).\n\n"
               "namespace stx_auxlib::math::detail {\n\n"
               "struct ExpEntry final {\n"
               "    double hi;\n    double lo;\n};\n\n"
               "// 256 entries of 16 bytes: 4 KiB.\n"
               "alignas(64) inline constexpr ExpEntry exp_table_256[256] = {\n",
               output);
    for (int j = 0; j < 256; ++j) {
        const wide::Wide value = wide::exp_series(angle(j));
        const wide::Wide entry = wide::two_sum(value.hi, value.lo);
        std::fprintf(output, "    {%a, %a}%s\n", entry.hi, entry.lo + 0.0, j == 255 ? "" : ",");
    }
    std::fputs("};\n", output);

    // ln2/256 for Cody-Waite reduction: two 34-bit parts and a double rest.
    const double t1 = wide::ln2_1 / 256.0;
    const double t2 = wide::ln2_2 / 256.0;
    const double t3 = wide::ln2_3 / 256.0;
    const double p1 = truncate_34(t1);
    const wide::Wide rest = wide::add(wide::Wide{t1 - p1, 0.0},
                                      wide::add(wide::Wide{t2, 0.0}, wide::Wide{t3, 0.0}));
    const double p2 = truncate_34(rest.hi);
    const double p3 = (rest.hi - p2) + rest.lo;
    std::fprintf(output,
                 "\n// ln2/256 = step_1 + step_2 + step_3 (~120 bits); step_1 and step_2 have\n"
                 "// 34 significant bits, so q * step_1 and q * step_2 are exact for |q| < 2^19.\n"
                 "inline constexpr double exp_step_1 = %a;\n"
                 "inline constexpr double exp_step_2 = %a;\n"
                 "inline constexpr double exp_step_3 = %a;\n\n"
                 "} // namespace stx_auxlib::math::detail\n",
                 p1, p2, p3);
    std::fclose(output);
    return 0;
}
