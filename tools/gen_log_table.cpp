// Generates src/math/log_table128.hpp: for 128 buckets of z in
// [0.6873, 1.3745), the rounded reciprocal inv of the bucket's centre and
// -log(inv) as hi + lo, plus the constants the log kernels need (ln 2,
// 1/ln 2, log10(2) and 1/ln 10 as split doubles). Computed with the
// double-double reference in tests/reference/wide.hpp.
//
// log x = k*ln2 + log z, and log z = -log(inv) + log1p(z*inv - 1) holds
// exactly for the rounded inv, so inv needs no particular accuracy. The
// bucket centred on 1 has inv = 1 and -log(inv) = 0, which keeps log(1) = 0
// and log2(2^k) = k exact.
//
// Usage: gen_log_table <output header>

#include "../tests/reference/wide.hpp"

#include <bit>
#include <cmath>
#include <cstdint>
#include <cstdio>

namespace {

// Buckets are 2^45 bit patterns wide (1/256 below 1, 1/128 above), offset
// by half a bucket so that 1 is a bucket centre.
constexpr std::uint64_t log_offset_bits = 0x3fe6000000000000ULL - (std::uint64_t{1} << 44);
constexpr std::uint64_t bucket_bits = std::uint64_t{1} << 45;

// Keeps the leading `bits` significant bits.
double truncate(const double value, const int bits) {
    const std::uint64_t pattern = std::bit_cast<std::uint64_t>(value);
    const std::uint64_t kept = pattern & ~((std::uint64_t{1} << (53 - bits)) - 1);
    const double result = std::bit_cast<double>(kept);
    return result;
}

wide::Wide normalized(const wide::Wide value) {
    const wide::Wide sum = wide::two_sum(value.hi, value.lo);
    const wide::Wide result{sum.hi + 0.0, sum.lo + 0.0};
    return result;
}

} // namespace

int main(const int argument_count, char** const arguments) {
    if (argument_count != 2) {
        std::fputs("usage: gen_log_table <output header>\n", stderr);
        return 2;
    }
    std::FILE* const output = std::fopen(arguments[1], "w");
    if (output == nullptr) return 1;
    std::fprintf(output,
                 "#pragma once\n\n"
                 "// Generated by tools/gen_log_table.cpp. Do not edit by hand.\n"
                 "// Bucket i covers the 2^45 bit patterns from log_offset_bits + i * 2^45; inv\n"
                 "// is the rounded reciprocal of its centre and -log(inv) = logc_hi + logc_lo\n"
                 "// (reference error ~1e-32).\n\n"
                 "#include <cstdint>\n\n"
                 "namespace stx_auxlib::math::detail {\n\n"
                 "struct LogEntry final {\n"
                 "    double inv;\n    double logc_hi;\n    double logc_lo;\n};\n\n"
                 "inline constexpr std::uint64_t log_offset_bits = 0x%016llxULL;\n\n"
                 "// 128 entries of 24 bytes: 3 KiB.\n"
                 "alignas(64) inline constexpr LogEntry log_table_128[128] = {\n",
                 static_cast<unsigned long long>(log_offset_bits));
    for (std::uint64_t i = 0; i < 128; ++i) {
        const std::uint64_t centre_bits = log_offset_bits + i * bucket_bits + bucket_bits / 2;
        const double centre = std::bit_cast<double>(centre_bits);
        const double inv = 1.0 / centre;
        const wide::Wide logc = normalized(wide::negate(wide::log_reference(inv)));
        std::fprintf(output, "    {%a, %a, %a}%s\n", inv, logc.hi, logc.lo, i == 127 ? "" : ",");
    }
    std::fputs("};\n", output);

    // ln 2 with a 42-bit head, so k * head is exact for |k| < 2^11.
    const wide::Wide ln2{wide::ln2_1, wide::ln2_2};
    const double ln2_hi = truncate(ln2.hi, 42);
    const wide::Wide ln2_rest = wide::add(ln2, wide::Wide{-ln2_hi, 0.0});
    const wide::Wide inv_ln2 = normalized(wide::divide(wide::Wide{1.0, 0.0}, ln2));
    const wide::Wide ln10 = wide::log_reference(10.0);
    const wide::Wide inv_ln10 = normalized(wide::divide(wide::Wide{1.0, 0.0}, ln10));
    const wide::Wide log10_2 = normalized(wide::multiply(ln2, inv_ln10));
    const double log10_2_hi = truncate(log10_2.hi, 42);
    const wide::Wide log10_2_rest = wide::add(log10_2, wide::Wide{-log10_2_hi, 0.0});
    std::fprintf(output,
                 "\n// ln 2 = log_ln2_hi + log_ln2_lo; the head has 42 significant bits, so\n"
                 "// k * log_ln2_hi is exact for |k| < 2^11. The same split for log10(2).\n"
                 "inline constexpr double log_ln2_hi = %a;\n"
                 "inline constexpr double log_ln2_lo = %a;\n"
                 "inline constexpr double log_log10_2_hi = %a;\n"
                 "inline constexpr double log_log10_2_lo = %a;\n"
                 "// 1/ln 2 and 1/ln 10 as double-doubles.\n"
                 "inline constexpr double log_inv_ln2_hi = %a;\n"
                 "inline constexpr double log_inv_ln2_lo = %a;\n"
                 "inline constexpr double log_inv_ln10_hi = %a;\n"
                 "inline constexpr double log_inv_ln10_lo = %a;\n\n"
                 "} // namespace stx_auxlib::math::detail\n",
                 ln2_hi, ln2_rest.hi + ln2_rest.lo, log10_2_hi, log10_2_rest.hi + log10_2_rest.lo,
                 inv_ln2.hi, inv_ln2.lo, inv_ln10.hi, inv_ln10.lo);
    std::fclose(output);
    return 0;
}
